import { readFile, writeFile, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import subsetFont from 'subset-font';
const root = fileURLToPath(new URL('../', import.meta.url));
async function sourceFiles(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  return (await Promise.all(entries.map(entry => entry.isDirectory() ? sourceFiles(path.join(dir, entry.name)) : /\.(tsx?|json)$/.test(entry.name) ? [path.join(dir, entry.name)] : []))).flat();
}
const files = [...await sourceFiles(path.join(root, 'src/landing')), path.join(root, 'src/components/shared/FeedbackWidget.tsx')];
const text = (await Promise.all(files.map(file => readFile(file, 'utf8')))).join('') + Array.from({length: 224}, (_, i) => String.fromCodePoint(32 + i)).join('');
const characters = [...new Set(text)].sort().join('');
const fontPath = path.join(root, 'src/assets/landing/fonts/');
const original = await readFile(fontPath + 'landing-rounded.woff2');
// Preserve both wght and ROND variation axes and all shaping features.
const result = await subsetFont(original, characters, { targetFormat: 'woff2' });
if (result.length >= original.length) throw new Error('Landing subset must be smaller than its source');
await writeFile(fontPath + 'landing-rounded-ui.woff2', result);
function ranges(points) {
  const sorted = [...new Set(points)].sort((a, b) => a - b);
  const runs = [];
  for (const n of sorted) { const last = runs.at(-1); if (last && n === last[1] + 1) last[1] = n; else runs.push([n,n]); }
  return runs.map(([a,b]) => 'U+' + a.toString(16) + (a === b ? '' : '-' + b.toString(16))).join(',');
}
const codes = new Set([...characters].map(c => c.codePointAt(0)));
const excluded = [];
let from = 0;
for (const n of [...codes].sort((a,b)=>a-b)) { if (n > from) excluded.push('U+' + from.toString(16) + '-' + (n-1).toString(16)); from = n+1; }
excluded.push('U+' + from.toString(16) + '-10ffff');
await writeFile(path.join(root, 'src/landing/landing-fonts.generated.css'), `/* Generated by npm run fonts:landing. Preserve both variable axes. */
@font-face {font-family:'Banana Rounded';src:url('../assets/landing/fonts/landing-rounded-ui.woff2') format('woff2');font-weight:200 900;font-style:normal;font-display:swap;unicode-range:${ranges(codes)};}
@font-face {font-family:'Banana Rounded Fallback';src:url('../assets/landing/fonts/landing-rounded.woff2') format('woff2');font-weight:200 900;font-style:normal;font-display:swap;unicode-range:${excluded.join(',')};}
`);
console.log(JSON.stringify({ characters: characters.length, original: original.length, subset: result.length, saving: `${(100 * (1 - result.length / original.length)).toFixed(1)}%` }));
