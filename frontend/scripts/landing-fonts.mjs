import { readFile, writeFile, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import subsetFont from 'subset-font';
const root = fileURLToPath(new URL('../', import.meta.url));
async function sourceFiles(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  return (await Promise.all(entries.map(entry => entry.isDirectory() ? sourceFiles(path.join(dir, entry.name)) : /\.(tsx?|json)$/.test(entry.name) ? [path.join(dir, entry.name)] : []))).flat();
}
const files = [...await sourceFiles(path.join(root, 'src/landing')), path.join(root, 'src/components/shared/FeedbackWidget.tsx')];
const sources = await Promise.all(files.map(async file => ({ file, text: await readFile(file, 'utf8') })));
const latin = Array.from({length: 224}, (_, i) => String.fromCodePoint(32 + i)).join('');
const text = sources.map(source => source.text).join('') + latin;
const characters = [...new Set(text)].sort().join('');
// Keep the homepage's typography independent of long gallery descriptions.
// Other known characters retain the same face in a disjoint, on-demand subset.
const homeGalleryFiles = new Set(['GalleryCurvedShowcase.tsx', 'CurvedGallery.tsx', 'WheelDeck.tsx', 'DeckOverview.tsx', 'homeDeckNavigation.tsx']);
const manifest = JSON.parse(await readFile(path.join(root, 'src/landing/gallery/manifest.json'), 'utf8'));
const homeText = sources.filter(({ file }) => !file.includes('.test.') &&
  (!file.includes(path.sep + 'gallery' + path.sep) || homeGalleryFiles.has(path.basename(file))))
  .map(source => source.text).join('') + manifest.map(deck => Object.values(deck.title).join('')).join('') + latin;
const homeCharacters = new Set(homeText);
// The Chinese brand also appears in the English footer.
const isShared = c => c.codePointAt(0) < 0x3000 || '蕉幻'.includes(c);
const groups = [
  { name: 'landing-rounded-latin.woff2', text: [...characters].filter(isShared).join('') },
  { name: 'landing-rounded-ui.woff2', text: [...characters].filter(c => !isShared(c) && homeCharacters.has(c)).join('') },
  { name: 'landing-rounded-extended.woff2', text: [...characters].filter(c => !isShared(c) && !homeCharacters.has(c)).join('') },
];
const fontPath = path.join(root, 'src/assets/landing/fonts/');
const original = await readFile(fontPath + 'landing-rounded.woff2');
// Preserve both wght and ROND variation axes and all shaping features.
for (const group of groups) {
  const result = await subsetFont(original, group.text, { targetFormat: 'woff2' });
  if (result.length >= original.length) throw new Error('Landing subset must be smaller than its source');
  await writeFile(fontPath + group.name, result);
  group.bytes = result.length;
}
function ranges(points) {
  const sorted = [...new Set(points)].sort((a, b) => a - b);
  const runs = [];
  for (const n of sorted) { const last = runs.at(-1); if (last && n === last[1] + 1) last[1] = n; else runs.push([n,n]); }
  return runs.map(([a,b]) => 'U+' + a.toString(16) + (a === b ? '' : '-' + b.toString(16))).join(',');
}
const codes = new Set([...characters].map(c => c.codePointAt(0)));
const excluded = [];
let from = 0;
for (const n of [...codes].sort((a,b)=>a-b)) { if (n > from) excluded.push('U+' + from.toString(16) + '-' + (n-1).toString(16)); from = n+1; }
excluded.push('U+' + from.toString(16) + '-10ffff');
await writeFile(path.join(root, 'src/landing/landing-fonts.generated.css'), `/* Generated by npm run fonts:landing. Preserve both variable axes. */
${groups.map(group => `@font-face {font-family:'Banana Rounded';src:url('../assets/landing/fonts/${group.name}') format('woff2');font-weight:200 900;font-style:normal;font-display:swap;unicode-range:${ranges([...group.text].map(c => c.codePointAt(0)))};}`).join('\n')}
@font-face {font-family:'Banana Rounded Fallback';src:url('../assets/landing/fonts/landing-rounded.woff2') format('woff2');font-weight:200 900;font-style:normal;font-display:swap;unicode-range:${excluded.join(',')};}
`);
console.log(JSON.stringify({ characters: characters.length, original: original.length, groups: groups.map(group => ({ name: group.name, characters: [...group.text].length, bytes: group.bytes })) }));
